/*
Generated by gltfjsx (npx gltfjsx public/models/chameleon.glb --types), then adjusted by hand:
React 19 types, real model path, typed bones, own AnimationMixer so that the
per-frame order is always mixer.update() first, code second (see model contract).
*/
"use client";

import { useEffect, useMemo, useRef, type RefObject } from "react";
import * as THREE from "three";
import { useFrame, useGraph, type ThreeElements } from "@react-three/fiber";
import { useGLTF } from "@react-three/drei";
import type { GLTF } from "three/examples/jsm/loaders/GLTFLoader.js";
import { clone as cloneSkinned } from "three/examples/jsm/utils/SkeletonUtils.js";
import type { ModelTestControls } from "@/components/controls";

const MODEL_PATH = "/models/chameleon.glb";

type ActionName = "eyes_look" | "walk";

interface GLTFAction extends THREE.AnimationClip {
  name: ActionName;
}

type TailBoneName = `Tail_${"01" | "02" | "03" | "04" | "05" | "06" | "07" | "08" | "09" | "10" | "11" | "12"}`;

const TAIL_BONE_NAMES: readonly TailBoneName[] = [
  "Tail_01", "Tail_02", "Tail_03", "Tail_04", "Tail_05", "Tail_06",
  "Tail_07", "Tail_08", "Tail_09", "Tail_10", "Tail_11", "Tail_12",
];

type NodeMap = {
  Chameleon: THREE.SkinnedMesh;
  Chameleon_Eyes: THREE.SkinnedMesh;
  Hips: THREE.Bone;
  HeadLook: THREE.Bone;
  Head: THREE.Bone;
  Eye_L: THREE.Bone;
  Eye_R: THREE.Bone;
} & Record<TailBoneName, THREE.Bone>;

type GLTFResult = GLTF & {
  nodes: NodeMap;
  materials: {
    Chameleon_Skin: THREE.MeshStandardMaterial;
    Chameleon_Eye: THREE.MeshStandardMaterial;
  };
  animations: GLTFAction[];
};

const AXIS_X = new THREE.Vector3(1, 0, 0);
const AXIS_Z = new THREE.Vector3(0, 0, 1);
const scratchQuaternion = new THREE.Quaternion();

/** Rotates a bone around one of its own local axes, on top of its current pose. */
function rotateAroundLocalAxis(bone: THREE.Bone, axis: THREE.Vector3, radians: number) {
  if (radians === 0) return;
  bone.quaternion.multiply(scratchQuaternion.setFromAxisAngle(axis, radians));
}

function setVisibility(objects: readonly THREE.Object3D[], visible: boolean) {
  for (const object of objects) object.visible = visible;
}

type ChameleonModelProps = ThreeElements["group"] & {
  controlsRef: RefObject<ModelTestControls>;
};

export function ChameleonModel({ controlsRef, ...groupProps }: ChameleonModelProps) {
  const group = useRef<THREE.Group>(null);
  const { scene, animations } = useGLTF(MODEL_PATH) as unknown as GLTFResult;
  const clonedScene = useMemo(() => cloneSkinned(scene), [scene]);
  const { nodes, materials } = useGraph(clonedScene) as unknown as Pick<GLTFResult, "nodes" | "materials">;

  const mixer = useMemo(() => new THREE.AnimationMixer(clonedScene), [clonedScene]);
  const actions = useRef<Record<ActionName, THREE.AnimationAction> | null>(null);
  const axesHelpers = useRef<THREE.AxesHelper[]>([]);
  const headLookRestQuaternion = useRef(new THREE.Quaternion());

  useEffect(() => {
    const walkClip = animations.find((clip) => clip.name === "walk");
    const eyesLookClip = animations.find((clip) => clip.name === "eyes_look");
    if (!walkClip || !eyesLookClip) throw new Error("chameleon.glb is missing the walk / eyes_look clips");

    // Both actions stay enabled: an enabled action with weight 0 makes the mixer
    // restore its bones to the rest pose, so code-driven offsets never accumulate.
    const walk = mixer.clipAction(walkClip);
    const eyesLook = mixer.clipAction(eyesLookClip);
    walk.paused = true; // scrubbed by phase, never by time
    walk.play();
    eyesLook.play();
    actions.current = { walk, eyes_look: eyesLook };

    headLookRestQuaternion.current.copy(nodes.HeadLook.quaternion);

    const helperBones = [nodes.HeadLook, nodes.Eye_L, nodes.Eye_R, nodes.Tail_01, nodes.Tail_06, nodes.Tail_12];
    axesHelpers.current = helperBones.map((bone) => {
      const helper = new THREE.AxesHelper(0.1);
      bone.add(helper);
      return helper;
    });

    return () => {
      axesHelpers.current.forEach((helper) => {
        helper.removeFromParent();
        helper.dispose();
      });
      axesHelpers.current = [];
      mixer.stopAllAction();
      actions.current = null;
    };
  }, [animations, mixer, nodes]);

  useFrame((_, delta) => {
    const clips = actions.current;
    if (!clips) return;
    const controls = controlsRef.current;

    clips.walk.time = controls.walkPhase * clips.walk.getClip().duration;
    clips.walk.setEffectiveWeight(controls.clip === "walk" ? 1 : 0);
    clips.eyes_look.setEffectiveWeight(controls.clip === "eyes_look" ? 1 : 0);

    // 1) clips first ...
    mixer.update(delta);

    // 2) ... then code on top of the pose.
    // HeadLook: absolute rotation (clips never touch it). Yaw = local Z, pitch = local X.
    nodes.HeadLook.quaternion.copy(headLookRestQuaternion.current);
    rotateAroundLocalAxis(nodes.HeadLook, AXIS_Z, controls.headLookYaw);
    rotateAroundLocalAxis(nodes.HeadLook, AXIS_X, controls.headLookPitch);

    // Eye_L: local +Y is the rest gaze direction; test sliders turn it around Z and X.
    rotateAroundLocalAxis(nodes.Eye_L, AXIS_Z, controls.eyeLeftYaw);
    rotateAroundLocalAxis(nodes.Eye_L, AXIS_X, controls.eyeLeftPitch);

    // Tail_01..12: additive on top of the clip pose. Twist = local X, sway = local Z.
    for (const tailBoneName of TAIL_BONE_NAMES) {
      const tailBone = nodes[tailBoneName];
      rotateAroundLocalAxis(tailBone, AXIS_X, controls.tailTwist);
      rotateAroundLocalAxis(tailBone, AXIS_Z, controls.tailSway);
    }

    setVisibility(axesHelpers.current, controls.showBoneAxes);
  });

  return (
    <group ref={group} {...groupProps} dispose={null}>
      <group name="Scene">
        <group name="Chameleon_Rig">
          <primitive object={nodes.Hips} />
        </group>
        <skinnedMesh
          name="Chameleon"
          geometry={nodes.Chameleon.geometry}
          material={materials.Chameleon_Skin}
          skeleton={nodes.Chameleon.skeleton}
        />
        <skinnedMesh
          name="Chameleon_Eyes"
          geometry={nodes.Chameleon_Eyes.geometry}
          material={materials.Chameleon_Eye}
          skeleton={nodes.Chameleon_Eyes.skeleton}
        />
      </group>
    </group>
  );
}

useGLTF.preload(MODEL_PATH);
